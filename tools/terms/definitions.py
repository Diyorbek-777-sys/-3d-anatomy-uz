# --- the sentence ---------------------------------------------------------

def _entity_of(name):
    """The subject of the sentence, from the hand-written table."""
    lowered = name.lower().replace('*', '')
    best = None
    for phrase, description in ENTITY.items():
        if re.search(r'(?<![a-z])' + re.escape(phrase) + r'(?![a-z])', lowered):
            if best is None or len(phrase) > len(best[0]):
                best = (phrase, description)
    return best[1] if best else None


def _uz_head(name, uzName):
    """What the structure is, from the English name and then the Uzbek one."""
    english = [
        word.strip('(),.').lower()
        for word in re.sub(r'\s*\([^)]*\)', ' ', name.replace('*', '')).split()
    ]
    for word in reversed(english):
        if word in REGION_WORD:
            continue
        if word in EN_HEAD:
            return EN_HEAD[word]

    words = [
        word for word in uzName.split()
        if not re.fullmatch(r'\([^)]*\)', word) and not re.fullmatch(r'[\(\)\[\].,*]+', word)
    ]
    for word in reversed(words):
        last = word.strip('(),.').lower()
        for ending, kind in UZ_HEAD:
            if last == ending:
                return kind
        for ending, kind in UZ_HEAD:
            if last.endswith(ending) and len(last) - len(ending) <= 2:
                return kind
    return None


def _uz_region(uzName):
    """Where the structure sits, from the Uzbek name."""
    words = set(re.findall(r'[\w\u02bb\u02bc\-]+', uzName.lower()))
    for needle, where in UZ_REGION:
        if needle in words:
            return where
    return None


