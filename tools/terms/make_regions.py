# Which region wins when a name mentions several.
PRIORITY = ['pelvis', 'head', 'neck', 'thorax', 'abdomen', 'back', 'upper_limb', 'lower_limb']


def region_of(base):
    lowered = base.lower()
    found = set()
    for word, region in WORDS.items():
        if word in lowered:
            found.add(region)
    for region in PRIORITY:
        if region in found:
            return region
    return None


