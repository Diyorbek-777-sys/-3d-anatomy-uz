// Regenerates src/data/translations.js from public/data/translations/*.json.
//
// The JSON files under public/ are the source of truth: they are what the app
// actually fetches at runtime. The module in src/ only exists so the very
// first paint already has the strings it needs, before the fetch resolves.
//
// Keeping the two in step by hand is how dictionaries drift, so this writes the
// src/ copy from the public/ copy. Run it after editing any dictionary:
//
//   node tools/sync-translations.mjs
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const TRANSLATIONS_DIR = path.resolve('public/data/translations');
const OUTPUT = path.resolve('src/data/translations.js');

// The order the dictionaries appear in the generated file.
const ORDER = ['uz', 'en', 'it'];

const identifier = code => `translations${code.charAt(0).toUpperCase()}${code.slice(1)}`;

const files = (await readdir(TRANSLATIONS_DIR)).filter(name => name.endsWith('.json'));
const codes = files.map(name => path.basename(name, '.json'));
const ordered = [...ORDER.filter(code => codes.includes(code)), ...codes.filter(code => !ORDER.includes(code))];

const dictionaries = new Map();
for (const code of ordered) {
  const raw = await readFile(path.join(TRANSLATIONS_DIR, `${code}.json`), 'utf8');
  dictionaries.set(code, JSON.parse(raw));
}

// Every dictionary must carry exactly the same keys, or the fallback would
// silently miss a string that the fetched dictionary has.
const reference = [...dictionaries.values()][0];
const referenceKeys = Object.keys(reference);
for (const [code, dictionary] of dictionaries) {
  const keys = Object.keys(dictionary);
  const missing = referenceKeys.filter(key => !(key in dictionary));
  const extra = keys.filter(key => !(key in reference));
  if (missing.length || extra.length) {
    throw new Error(
      `${code}.json does not match the reference key set.\n` +
      `  missing: ${missing.join(', ') || '(none)'}\n` +
      `  extra:   ${extra.join(', ') || '(none)'}`
    );
  }
}

const body = ordered
  .map(code => {
    const entries = Object.entries(dictionaries.get(code))
      .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)}`)
      .join(',\n');
    return `export const ${identifier(code)} = {\n${entries}\n};`;
  })
  .join('\n\n');

const file = `// Fallback dictionaries, used before translations/*.json arrives.
//
// GENERATED by tools/sync-translations.mjs — do not edit by hand.
// Source of truth: public/data/translations/<lang>.json
import { DEFAULT_LANG } from './languages.js';

${body}

// Every language the atlas ships, keyed by code. The store seeds itself with
// these, and loadAllData() replaces them with the fetched copies.
export const FALLBACK_TRANSLATIONS = {
${ordered.map(code => `  ${code}: ${identifier(code)}`).join(',\n')}
};

export { DEFAULT_LANG };
`;

await writeFile(OUTPUT, file);
console.log(`sync-translations: wrote ${path.relative(process.cwd(), OUTPUT)} (${ordered.join(', ')})`);
